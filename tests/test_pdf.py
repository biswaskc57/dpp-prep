"""PDF route: the same workflow on PDF versions of the W-100 documents.
Generated by scripts/make_pdfs.py; the thermal section of D3 is on page 2."""
from __future__ import annotations

from pathlib import Path

from dpp_prep.extract import StandInExtractor
from dpp_prep.models import State
from dpp_prep.service import PreparationService

ROOT = Path(__file__).resolve().parents[1]
PDF = ROOT / "data/w100/pdf"
ERP = ROOT / "data/w100/structured/erp_product_record.json"


def run(*names):
    svc = PreparationService(ROOT / "config/elements_w100.yaml",
                             StandInExtractor(ROOT / "config/standin_patterns_w100.yaml"))
    svc.start_run([PDF / f"{n}.pdf" for n in names] + [ERP])
    svc.prepare_product()
    return svc


def test_P01_pdf_baseline_all_elements_checked():
    svc = run("D1_datasheet", "D2_supplier_declaration", "D3_performance_report")
    assert {r.state for r in svc.records.values()} == {State.CHECKED}


def test_P02_evidence_names_the_page():
    svc = run("D1_datasheet", "D2_supplier_declaration", "D3_performance_report")
    pages = {p.evidence.source: p.evidence.page for p in svc.records["E06"].proposals}
    assert pages == {"D1_datasheet.pdf": 1, "D3_performance_report.pdf": 2}
    assert svc.records["E03"].proposals[0].evidence.page == 1


def test_P03_pdf_conflict_still_flagged():
    svc = run("D1_datasheet", "D2_supplier_declaration", "V2_D3_uw_conflict")
    assert svc.records["E06"].state == State.FLAGGED
